#!/usr/bin/env python3
"""Rasterises DejaVu Sans into 8-bit alpha glyph atlases for the on-screen UI (source/font.inc).

Usage: python3 tools/gen_font.py fonts source/font.inc
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

src, dst = sys.argv[1], sys.argv[2]
FULL = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xA0, 0x100)] + list("←→↑↓○✕△□·…–•‹›")
# UI text only needs ASCII plus the letters used by the UI languages; game titles use the title font
UI = [chr(c) for c in range(0x20, 0x7F)] + list("åäöÅÄÖéèêëüÜáàíóúñçßøØæÆ×·…–•‹›")
# (name, file, pixel size) for 1080p and 720p layouts
FONTS = [
    ("f1080_tiny", "DejaVuSans.ttf", 22, UI), ("f1080_small", "DejaVuSans.ttf", 28, UI), ("f1080_body", "DejaVuSans.ttf", 36, FULL), ("f1080_title", "DejaVuSans-Bold.ttf", 64, FULL),
    ("f720_tiny", "DejaVuSans.ttf", 15, UI), ("f720_small", "DejaVuSans.ttf", 19, UI), ("f720_body", "DejaVuSans.ttf", 24, FULL), ("f720_title", "DejaVuSans-Bold.ttf", 43, FULL),
]

def pack4(img):
    """8-bit alpha -> 4 bits per pixel, two pixels per byte (high nibble first), rows padded."""
    w, h = img.size
    px = img.tobytes()
    out = bytearray()
    for y in range(h):
        row = px[y * w:(y + 1) * w]
        for x in range(0, w, 2):
            a = (row[x] + 8) // 17
            b = (row[x + 1] + 8) // 17 if x + 1 < w else 0
            out.append((min(a, 15) << 4) | min(b, 15))
    return out

out = open(dst, "w", encoding="utf-8")
out.write("// Generated by tools/gen_font.py from DejaVu Sans (see fonts/DejaVu-LICENSE). 4-bit alpha. Do not edit.\n")
for name, fname, size, CHARS in FONTS:
    font = ImageFont.truetype(os.path.join(src, fname), size)
    ascent, descent = font.getmetrics()
    data = bytearray()
    glyphs = []
    for ch in CHARS:
        bbox = font.getbbox(ch)            # relative to the drawing origin (top-left, ascent-based)
        adv = int(round(font.getlength(ch)))
        if bbox is None or bbox[2] <= bbox[0]:
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, len(data)))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        glyphs.append((ord(ch), w, h, x0, y0, adv, len(data)))
        data += pack4(img)
    out.write("static const uint8_t %s_data[] = {%s};\n" % (name, ",".join(str(b) for b in data)))
    out.write("static const Glyph %s_glyphs[] = {\n" % name)
    for g in glyphs:
        out.write("\t{%d, %d, %d, %d, %d, %d, %d},\n" % g)
    out.write("};\n")
    out.write("static const Font %s = {%s_glyphs, %d, %s_data, %d};\n\n" % (name, name, len(glyphs), name, ascent + descent))
# Button symbols, sized to the body font's cap height and placed by their visible ink, so the
# bottom of every symbol sits exactly on the baseline of capital letters (the circle may overshoot
# by one pixel, as round letters do).
def ink_rows(img, thr=128):
    w, h = img.size
    px = img.tobytes()
    rows = [y for y in range(h) if max(px[y * w:(y + 1) * w]) >= thr]
    return rows[0], rows[-1]

for name, body in (("f1080_sym", 36), ("f720_sym", 24)):
    bodyfont = ImageFont.truetype(os.path.join(src, "DejaVuSans.ttf"), body)
    eb = bodyfont.getbbox("E")
    eimg = Image.new("L", (eb[2] - eb[0], eb[3] - eb[1]), 0)
    ImageDraw.Draw(eimg).text((-eb[0], -eb[1]), "E", font=bodyfont, fill=255)
    et, ebot = ink_rows(eimg)
    cap_top, cap_bottom = eb[1] + et, eb[1] + ebot        # ink rows of a capital, from the text top
    cap_h = cap_bottom - cap_top + 1
    data = bytearray()
    glyphs = []
    for ch in "△○✕□↑↓←→":
        overshoot = 1 if ch == "○" else 0
        target_h = cap_h + 2 * overshoot
        size, img = body, None
        for _ in range(12):   # find the font size whose ink height matches the target
            f = ImageFont.truetype(os.path.join(src, "DejaVuSans.ttf"), size)
            b = f.getbbox(ch)
            cand = Image.new("L", (b[2] - b[0], b[3] - b[1]), 0)
            ImageDraw.Draw(cand).text((-b[0], -b[1]), ch, font=f, fill=255)
            t, bt = ink_rows(cand)
            ink_h = bt - t + 1
            img, ink_top = cand.crop((0, t, cand.width, bt + 1)), 0
            if ink_h == target_h:
                break
            size = max(6, size + (1 if ink_h < target_h else -1))
        if img.height != target_h:
            img = img.resize((max(1, round(img.width * target_h / img.height)), target_h), Image.LANCZOS)   # keep proportions
        w, h = img.size
        top = cap_bottom - h + 1 + overshoot     # ink bottom on the capital baseline
        glyphs.append((ord(ch), w, h, 0, top, int(round(f.getlength(ch))), len(data)))
        data += pack4(img)
    out.write("static const uint8_t %s_data[] = {%s};\n" % (name, ",".join(str(b) for b in data)))
    out.write("static const Glyph %s_glyphs[] = {\n" % name)
    for gl in glyphs:
        out.write("\t{%d, %d, %d, %d, %d, %d, %d},\n" % gl)
    out.write("};\n")
    out.write("static const Font %s = {%s_glyphs, %d, %s_data, %d};\n\n" % (name, name, len(glyphs), name, 0))
    out.write("static const int %s_cap_top = %d, %s_cap_bottom = %d;\n\n" % (name, cap_top, name, cap_bottom))
# Face-button symbols, pre-composed on a square canvas the size of the button disc (1.5x the
# cap height). Each symbol is rendered large, cropped to its ink box in both directions, scaled
# so its larger side is 55 % of the disc, and placed with the ink box centred exactly on the
# canvas centre. The UI draws the disc and the glyph at the same top-left corner.
SS = 8   # supersampling factor for placement and downscaling
for name, body in (("f1080_btn", 36), ("f720_btn", 24)):
    bodyfont = ImageFont.truetype(os.path.join(src, "DejaVuSans.ttf"), body)
    eb = bodyfont.getbbox("E")
    eimg = Image.new("L", (eb[2] - eb[0], eb[3] - eb[1]), 0)
    ImageDraw.Draw(eimg).text((-eb[0], -eb[1]), "E", font=bodyfont, fill=255)
    et, ebot = ink_rows(eimg)
    cap_h = ebot - et + 1
    d = cap_h * 3 // 2                       # disc diameter, same formula as disc_size() in ui.cpp
    target = cap_h * 1.5 * 0.55 * SS
    big = ImageFont.truetype(os.path.join(src, "DejaVuSans.ttf"), body * SS)
    data = bytearray()
    glyphs = []
    for ch in "△○✕□":
        b = big.getbbox(ch)
        img = Image.new("L", (b[2] - b[0], b[3] - b[1]), 0)
        ImageDraw.Draw(img).text((-b[0], -b[1]), ch, font=big, fill=255)
        img = img.crop(img.getbbox())        # ink box, both axes
        k = target / max(img.size)
        img = img.resize((max(1, round(img.width * k)), max(1, round(img.height * k))), Image.LANCZOS)
        canvas = Image.new("L", (d * SS, d * SS), 0)
        # a triangle's visual weight sits low (centroid 1/6 below the box centre): lift it a bit
        lift = round(img.height * 0.09) if ch == "△" else 0
        canvas.paste(img, ((d * SS - img.width) // 2, (d * SS - img.height) // 2 - lift))
        canvas = canvas.resize((d, d), Image.BOX)
        glyphs.append((ord(ch), d, d, 0, 0, d, len(data)))
        data += pack4(canvas)
    out.write("static const uint8_t %s_data[] = {%s};\n" % (name, ",".join(str(b) for b in data)))
    out.write("static const Glyph %s_glyphs[] = {\n" % name)
    for gl in glyphs:
        out.write("\t{%d, %d, %d, %d, %d, %d, %d},\n" % gl)
    out.write("};\n")
    out.write("static const Font %s = {%s_glyphs, %d, %s_data, %d};\n\n" % (name, name, len(glyphs), name, 0))

out.close()
print("wrote", dst)
