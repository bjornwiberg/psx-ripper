#!/usr/bin/env python3
"""Rasterises DejaVu Sans into 8-bit alpha glyph atlases for the on-screen UI (source/font.inc).

Usage: python3 tools/gen_font.py fonts source/font.inc
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

src, dst = sys.argv[1], sys.argv[2]
FULL = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xA0, 0x100)] + list("←→↑↓○✕△□·…–•‹›")
# UI text only needs ASCII plus the letters used by the UI languages; game titles use the title font
UI = [chr(c) for c in range(0x20, 0x7F)] + list("åäöÅÄÖéèêëüÜáàíóúñçßøØæÆ×·…–•‹›")
# (name, file, pixel size) for 1080p and 720p layouts
FONTS = [
    ("f1080_small", "DejaVuSans.ttf", 28, UI), ("f1080_body", "DejaVuSans.ttf", 36, FULL), ("f1080_title", "DejaVuSans-Bold.ttf", 64, FULL),
    ("f720_small", "DejaVuSans.ttf", 19, UI), ("f720_body", "DejaVuSans.ttf", 24, FULL), ("f720_title", "DejaVuSans-Bold.ttf", 43, FULL),
]

def pack4(img):
    """8-bit alpha -> 4 bits per pixel, two pixels per byte (high nibble first), rows padded."""
    w, h = img.size
    px = img.tobytes()
    out = bytearray()
    for y in range(h):
        row = px[y * w:(y + 1) * w]
        for x in range(0, w, 2):
            a = (row[x] + 8) // 17
            b = (row[x + 1] + 8) // 17 if x + 1 < w else 0
            out.append((min(a, 15) << 4) | min(b, 15))
    return out

out = open(dst, "w", encoding="utf-8")
out.write("// Generated by tools/gen_font.py from DejaVu Sans (see fonts/DejaVu-LICENSE). 4-bit alpha. Do not edit.\n")
for name, fname, size, CHARS in FONTS:
    font = ImageFont.truetype(os.path.join(src, fname), size)
    ascent, descent = font.getmetrics()
    data = bytearray()
    glyphs = []
    for ch in CHARS:
        bbox = font.getbbox(ch)            # relative to the drawing origin (top-left, ascent-based)
        adv = int(round(font.getlength(ch)))
        if bbox is None or bbox[2] <= bbox[0]:
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, len(data)))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        glyphs.append((ord(ch), w, h, x0, y0, adv, len(data)))
        data += pack4(img)
    out.write("static const uint8_t %s_data[] = {%s};\n" % (name, ",".join(str(b) for b in data)))
    out.write("static const Glyph %s_glyphs[] = {\n" % name)
    for g in glyphs:
        out.write("\t{%d, %d, %d, %d, %d, %d, %d},\n" % g)
    out.write("};\n")
    out.write("static const Font %s = {%s_glyphs, %d, %s_data, %d};\n\n" % (name, name, len(glyphs), name, ascent + descent))
# Button symbols, each rendered at the size where its height equals the body font's cap height,
# so they line up with capital letters (top and baseline) in the hint bar.
for name, body in (("f1080_sym", 36), ("f720_sym", 24)):
    bodyfont = ImageFont.truetype(os.path.join(src, "DejaVuSans.ttf"), body)
    cap = bodyfont.getbbox("E")
    cap_top, cap_h = cap[1], cap[3] - cap[1]
    data = bytearray()
    glyphs = []
    # optical corrections: (height factor, downward shift as a fraction of cap height)
    OPTICAL = {"○": (1.04, 0.06), "✕": (1.0, 0.08)}
    for ch in "△○✕□↑↓←→":
        hf, shift = OPTICAL.get(ch, (1.0, 0.0))
        target_h = int(round(cap_h * hf))
        size = body
        for _ in range(40):   # find the size whose glyph height matches the cap height
            f = ImageFont.truetype(os.path.join(src, "DejaVuSans.ttf"), size)
            b = f.getbbox(ch)
            if abs((b[3] - b[1]) - target_h) <= 0 or size < 6:
                break
            size = max(6, int(round(size * target_h / (b[3] - b[1]))))
            f2 = ImageFont.truetype(os.path.join(src, "DejaVuSans.ttf"), size)
            if abs((f2.getbbox(ch)[3] - f2.getbbox(ch)[1]) - target_h) <= 1:
                f, b = f2, f2.getbbox(ch)
                break
        x0, y0, x1, y1 = b
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255)
        if h != target_h:   # snap to the target height
            img = img.resize((w, target_h), Image.LANCZOS)
            h = target_h
        # yoff = cap top, so the symbol's top sits where a capital letter's top sits
        top = cap_top - (target_h - cap_h) // 2 + int(round(cap_h * shift))
        glyphs.append((ord(ch), w, h, x0, top, int(round(f.getlength(ch))), len(data)))
        data += pack4(img)
    out.write("static const uint8_t %s_data[] = {%s};\n" % (name, ",".join(str(b) for b in data)))
    out.write("static const Glyph %s_glyphs[] = {\n" % name)
    for gl in glyphs:
        out.write("\t{%d, %d, %d, %d, %d, %d, %d},\n" % gl)
    out.write("};\n")
    out.write("static const Font %s = {%s_glyphs, %d, %s_data, %d};\n\n" % (name, name, len(glyphs), name, 0))
out.close()
print("wrote", dst)
