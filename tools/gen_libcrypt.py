#!/usr/bin/env python3
"""Generates source/libcrypt.inc from db/libcrypt_serials.txt (one SXXX-NNNNN serial per line).

Usage: python3 tools/gen_libcrypt.py db/libcrypt_serials.txt source/libcrypt.inc
"""
import sys

src, dst = sys.argv[1], sys.argv[2]
rows = sorted({l.strip().replace("-", "") for l in open(src) if l.strip() and not l.startswith("#")})
with open(dst, "w") as f:
    f.write("// Generated by tools/gen_libcrypt.py from db/libcrypt_serials.txt. Do not edit.\n")
    f.write("static const char libcrypt_serials[][10] = {\n")
    for r in rows:
        f.write('\t"{}",\n'.format(r))
    f.write("};\n")
print(f"{len(rows)} LibCrypt serials written to {dst}")
