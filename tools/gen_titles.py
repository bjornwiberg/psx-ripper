#!/usr/bin/env python3
"""Generates source/titles.inc (serial -> title) from GameDB-PSX's PSX.titles.json.

Data: https://github.com/niemasd/GameDB-PSX (GPL-3.0).
Usage: python3 tools/gen_titles.py db/PSX.titles.json source/titles.inc
"""
import json
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
data = json.load(open(src, encoding="utf-8"))
serial = re.compile(r"^[A-Z]{4}-\d{5}$")
rows = sorted((k, v) for k, v in data.items() if serial.match(k))


def c_str(s):
    out = s.encode("utf-8").decode("utf-8").replace("\\", "\\\\").replace('"', '\\"')
    return '"' + out + '"'


# Compact layout: a key per title (prefix index * 100000 + number, e.g. SLUS-00553 -> SLUS, 553),
# and one string blob with the titles in key order (offsets are rebuilt at start-up).
prefixes = sorted({k[:4] for k, _ in rows})
pidx = {p: i for i, p in enumerate(prefixes)}
entries = sorted((pidx[k[:4]] * 100000 + int(k[5:]), v) for k, v in rows)
blob = bytearray()
offs = []
for _, v in entries:
    offs.append(len(blob))
    blob += v.encode("utf-8") + b"\0"

with open(dst, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_titles.py from GameDB-PSX (GPL-3.0). Do not edit.\n")
    f.write("static const char title_prefixes[][5] = {%s};\n" % ",".join('"%s"' % p for p in prefixes))
    f.write("static const uint32_t title_keys[] = {%s};\n" % ",".join(str(k) for k, _ in entries))
    f.write("static const unsigned char title_blob[] = {%s};\n" % ",".join(str(b) for b in blob))
print(f"{len(entries)} titles, {len(prefixes)} prefixes, {len(blob)} bytes of text -> {dst}")
