#!/usr/bin/env python3
"""Generates source/titles.inc (serial -> title) from GameDB-PSX's PSX.titles.json.

Data: https://github.com/niemasd/GameDB-PSX (GPL-3.0).
Usage: python3 tools/gen_titles.py db/PSX.titles.json source/titles.inc
"""
import json
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
data = json.load(open(src, encoding="utf-8"))
serial = re.compile(r"^[A-Z]{4}-\d{5}$")
rows = sorted((k, v) for k, v in data.items() if serial.match(k))


def c_str(s):
    out = s.encode("utf-8").decode("utf-8").replace("\\", "\\\\").replace('"', '\\"')
    return '"' + out + '"'


with open(dst, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_titles.py from GameDB-PSX (GPL-3.0). Do not edit.\n")
    f.write("static const struct { char serial[10]; const char *title; } psx_titles[] = {\n")
    for k, v in rows:
        f.write('\t{{"{}", {}}},\n'.format(k.replace("-", ""), c_str(v)))
    f.write("};\n")
print(f"{len(rows)} titles written to {dst}")
